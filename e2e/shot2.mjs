import { chromium } from "@playwright/test";
const out = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 860 } });
const p = await ctx.newPage();
await p.request.post("http://localhost:8000/sim/reset");
await p.goto("http://localhost:3000/payments", { waitUntil: "networkidle" });
await p.getByRole("button", { name: /Syarikat Kertas Sdn Bhd RM 18,400/ }).click();
await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/sheet.png` });
await p.keyboard.press("Escape");
await p.request.post("http://localhost:8000/sim/malicious-invoice");
await p.goto("http://localhost:3000/", { waitUntil: "networkidle" });
await p.getByTestId("review-approval").first().click();
await p.waitForTimeout(800);
await p.getByRole("button", { name: "Ask why" }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/approval.png` });
await b.close();
