import { chromium } from "@playwright/test";
const out = process.argv[2];
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } });
await ctx.addInitScript(() => localStorage.setItem("helm-theme", "dark"));
const p = await ctx.newPage();
const errs = []; p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await p.goto("http://localhost:3000/forecast", { waitUntil: "networkidle" });
await p.getByRole("tab", { name: "Cash flow" }).click();
await p.waitForTimeout(600);
await p.locator("svg.recharts-surface").first().click({ position: { x: 560, y: 120 } });
await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/flow.png` });
await p.goto("http://localhost:3000/cash", { waitUntil: "networkidle" }); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/cash.png` });
await p.goto("http://localhost:3000/collections", { waitUntil: "networkidle" }); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/coll.png`, clip: { x: 0, y: 0, width: 1440, height: 1000 } });
console.log("errors", errs.length, errs.slice(0,3));
await b.close();
